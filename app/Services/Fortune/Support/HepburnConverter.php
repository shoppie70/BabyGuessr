<?php

namespace App\Services\Fortune\Support;

class HepburnConverter
{
    /**
     * ひらがな/カタカナを大文字ヘボン式ローマ字に変換
     */
    public static function convert(string $kana): string
    {
        // カタカナを全角ひらがなに変換
        $text = mb_convert_kana($kana, 'cHV', 'UTF-8');

        // 拗音・促音・長音対応
        $mapping = [
            'きゃ' => 'KYA', 'きゅ' => 'KYU', 'きょ' => 'KYO',
            'しゃ' => 'SHA', 'しゅ' => 'SHU', 'しょ' => 'SHO',
            'ちゃ' => 'CHA', 'ちゅ' => 'CHU', 'ちょ' => 'CHO',
            'にゃ' => 'NYA', 'にゅ' => 'NYU', 'にょ' => 'NYO',
            'ひゃ' => 'HYA', 'ひゅ' => 'HYU', 'ひょ' => 'HYO',
            'みゃ' => 'MYA', 'みゅ' => 'MYU', 'みょ' => 'MYO',
            'りゃ' => 'RYA', 'りゅ' => 'RYU', 'りょ' => 'RYO',
            'ぎゃ' => 'GYA', 'ぎゅ' => 'GYU', 'ぎょ' => 'GYO',
            'じゃ' => 'JA',  'じゅ' => 'JU',  'じょ' => 'JO',
            'びゃ' => 'BYA', 'びゅ' => 'BYU', 'びょ' => 'BYO',
            'ぴゃ' => 'PYA', 'ぴゅ' => 'PYU', 'ぴょ' => 'PYO',

            // 促音 (っ/ッ)
            'っち' => 'TCHI', 'っちゃ' => 'TCHA', 'っちゅ' => 'TCHU', 'ッチョ' => 'TCHO',
            'っか' => 'KKA', 'っき' => 'KKI', 'っく' => 'KKU', 'っけ' => 'KKE', 'っこ' => 'KKO',
            'っさ' => 'SSA', 'っし' => 'SSH', 'っす' => 'SSU', 'っせ' => 'SSE', 'っそ' => 'SSO',
            'った' => 'TTA', 'って' => 'TTE', 'っと' => 'TTO',
            'っぱ' => 'PPA', 'っぴ' => 'PPI', 'っぷ' => 'PPU', 'っぺ' => 'PPE', 'っぽ' => 'PPO',

            // 単音
            'あ' => 'A', 'い' => 'I', 'う' => 'U', 'え' => 'E', 'お' => 'O',
            'か' => 'KA', 'き' => 'KI', 'く' => 'KU', 'け' => 'KE', 'こ' => 'KO',
            'さ' => 'SA', 'し' => 'SHI', 'す' => 'SU', 'せ' => 'SE', 'そ' => 'SO',
            'た' => 'TA', 'ち' => 'CHI', 'つ' => 'TSU', 'て' => 'TE', 'と' => 'TO',
            'な' => 'NA', 'に' => 'NI', 'ぬ' => 'NU', 'ね' => 'NE', 'の' => 'NO',
            'は' => 'HA', 'ひ' => 'HI', 'ふ' => 'FU', 'へ' => 'HE', 'ほ' => 'HO',
            'ま' => 'MA', 'み' => 'MI', 'む' => 'MU', 'め' => 'ME', 'も' => 'MO',
            'や' => 'YA', 'ゆ' => 'YU', 'よ' => 'YO',
            'ら' => 'RA', 'り' => 'RI', 'る' => 'RU', 'れ' => 'RE', 'ろ' => 'RO',
            'わ' => 'WA', 'を' => 'O',  'ん' => 'N',
            'が' => 'GA', 'ぎ' => 'GI', 'ぐ' => 'GU', 'げ' => 'GE', 'ご' => 'GO',
            'ざ' => 'ZA', 'じ' => 'JI', 'ず' => 'ZU', 'ぜ' => 'ZE', 'ぞ' => 'ZO',
            'だ' => 'DA', 'ぢ' => 'JI', 'づ' => 'ZU', 'で' => 'DE', 'ど' => 'DO',
            'ば' => 'BA', 'び' => 'BI', 'ぶ' => 'BU', 'べ' => 'BE', 'ぼ' => 'BO',
            'ぱ' => 'PA', 'ぴ' => 'PI', 'ぷ' => 'PU', 'ぺ' => 'PE', 'ぽ' => 'PO',
        ];

        // 撥音 'ん' の直後が B, M, P の場合は 'M' に変換
        $result = strtr($text, $mapping);
        $result = preg_replace('/N([BMP])/', 'M$1', $result);

        // 長音（大文字連続など、ヘボン式では母音を重ねないかそのまま）
        // やまだ -> YAMADA
        // はな -> HANA
        return trim($result);
    }
}
